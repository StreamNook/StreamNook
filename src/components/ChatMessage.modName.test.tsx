import ChatMessage from './ChatMessage';

// A struck row learns who acted a moment after IRC struck it (EventSub). The
// row memo must let that repaint, or the name never shows.
type Compare = (prev: Record<string, unknown>, next: Record<string, unknown>) => boolean;
const compare = (ChatMessage as unknown as { compare: Compare }).compare;

const message = { id: 'm', user_id: '7', segments: [] };
const timeout = { type: 'timeout', duration: 600 };

describe('the chat row memo', () => {
  it('repaints when the moderator or the reason arrives', () => {
    const base = { message, moderationContext: timeout };
    expect(compare(base, { message, moderationContext: { ...timeout } })).toBe(true);
    expect(compare(base, { message, moderationContext: { ...timeout, by: 'kay_lee' } })).toBe(false);
    expect(
      compare(
        { message, moderationContext: { ...timeout, by: 'kay_lee' } },
        { message, moderationContext: { ...timeout, by: 'kay_lee', reason: 'spoilers' } },
      ),
    ).toBe(false);
  });
});
